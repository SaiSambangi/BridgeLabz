package com.day01;

public class DefaultValuesPrimitiveDataTypes {



	byte b;
	short s;
	int i;
	long l;
	float f;
	double d;
	char c;
	boolean bool;

	public static void main(String[] args) {
		
		DefaultValuesPrimitiveDataTypes o=new DefaultValuesPrimitiveDataTypes();

		System.out.println("byte = " + o.b);
		System.out.println("short = " + o.s);
		System.out.println("int = " + o.i);
		System.out.println("long = " + o.l);
		System.out.println("float = " + o.f);
		System.out.println("double = " + o.d);
		System.out.println("char = " + o.c);
		System.out.println("boolean = " + o.bool);

	}




}
